"""
Build the tiny SMOKE-TEST dataset used to check the whole pipeline end to end before real data exists.

    python scripts/make_smoke_data.py

Source: Ultralytics "coco128" (first 128 COCO train2017 images, AGPL-3.0 packaging of COCO, images
CC BY 4.0 / Flickr terms). coco8 was considered but has almost no vehicles, so coco128 is used and
filtered to images that contain at least one car / motorcycle / bicycle / bus / truck. COCO labels are
mapped to the project classes with convert_to_yolo.py (COCO has no auto-rickshaw class).

Output (kept apart from the real data on purpose):
  data_smoke/{train,val,test}/{images,labels}, data_smoke/data.yaml
NUMBERS COMPUTED ON THIS DATA ARE NOT PROJECT RESULTS. They only prove the code runs.
"""
from __future__ import annotations

import io
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

import numpy as np
import requests

ROOT = Path(__file__).resolve().parents[1]
URL = "https://github.com/ultralytics/assets/releases/download/v0.0.0/coco128.zip"
sys.path.insert(0, str(ROOT))
from trafficlib import CLASS_NAMES, read_yolo_labels  # noqa: E402


def main():
    out = ROOT / "data_smoke"
    dl = out / "_download"
    if not (dl / "coco128").exists():
        dl.mkdir(parents=True, exist_ok=True)
        print("downloading", URL)
        r = requests.get(URL, timeout=300)
        r.raise_for_status()
        with zipfile.ZipFile(io.BytesIO(r.content)) as z:
            for m in z.namelist():  # extract only images/labels, refuse path tricks
                if m.endswith("/") or ".." in m or m.startswith("/"):
                    continue
                if m.lower().endswith((".jpg", ".txt", ".yaml")):
                    z.extract(m, dl)
    src_img = dl / "coco128" / "images" / "train2017"
    src_lab = dl / "coco128" / "labels" / "train2017"

    # Map COCO-80 labels -> project classes (shared conversion script).
    mapped = out / "_mapped_labels"
    subprocess.run([sys.executable, str(ROOT / "scripts" / "convert_to_yolo.py"), "--source", "coco",
                    "--format", "yolo", "--names", "coco80", "--in-labels", str(src_lab),
                    "--out-labels", str(mapped)], check=True)

    # Keep images with >= 1 vehicle; deterministic 50/25/25 split (seed 42).
    keep = sorted(p for p in src_img.glob("*.jpg") if len(read_yolo_labels(mapped / (p.stem + ".txt"))) > 0)
    rng = np.random.default_rng(42)
    order = rng.permutation(len(keep))
    n_tr, n_va = len(keep) // 2, len(keep) // 4
    parts = {"train": order[:n_tr], "val": order[n_tr:n_tr + n_va], "test": order[n_tr + n_va:]}
    for split, idx in parts.items():
        for sub in ("images", "labels"):
            d = out / split / sub
            if d.exists():
                shutil.rmtree(d)  # data_smoke is fully generated by this script
            d.mkdir(parents=True)
        for k in idx:
            p = keep[k]
            shutil.copy2(p, out / split / "images" / p.name)
            shutil.copy2(mapped / (p.stem + ".txt"), out / split / "labels" / (p.stem + ".txt"))
    (out / "data.yaml").write_text("# SMOKE TEST ONLY (coco128 vehicles) - not project data\n"
                                   "train: train/images\nval: val/images\ntest: test/images\n"
                                   f"nc: {len(CLASS_NAMES)}\nnames: {CLASS_NAMES}\n")
    (out / "README.txt").write_text(
        "SMOKE-TEST DATA ONLY - NOT PART OF THE PROJECT DATASET.\n"
        "22 COCO images (from Ultralytics coco128) that contain at least one car / motorcycle / bicycle /\n"
        "bus / truck. Used only to check that the notebooks run end to end. Some are ordinary COCO\n"
        "photos where a vehicle is only in the background. The real data is in ../data/.\n")
    # Remove the raw 128-image download (fruit, animals, kitchens...) so it cannot be mistaken for
    # project data; only the filtered vehicle images above are kept.
    shutil.rmtree(dl, ignore_errors=True)
    shutil.rmtree(mapped, ignore_errors=True)
    print({s: len(v) for s, v in parts.items()}, "images with vehicles ->", out)


if __name__ == "__main__":
    main()
